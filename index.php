function renderPropCard(p){
  var st = p.status||'available';
  var stLabel = st==='sold'?'SOLD':st==='pending'?'UNDER CONTRACT':'FOR SALE';
  var badgeCls = st==='sold'?'gp-badge-sold':st==='pending'?'gp-badge-pending':'gp-badge-available';
  var img = p.images&&p.images.length
    ? '<img src="'+p.images[0]+'" alt="'+p.title+'" loading="lazy">'
    : '<div style="height:100%;display:flex;align-items:center;justify-content:center;font-size:48px;opacity:.2">🏠</div>';
  return '<div class="gp-prop-card" onclick="location.href='property.html?id='+p.id+''">'
    +'<div class="gp-prop-card-img">'+img+'<span class="gp-prop-badge '+badgeCls+'">'+stLabel+'</span></div>'
    +'<div class="gp-prop-card-body">'
    +'<div class="gp-prop-type">'+(p.property_type||'Single Family Home')+'</div>'
    +'<h3>'+p.title+'</h3>'
    +'<div class="gp-prop-city">'+(p.city||'')+(p.zip?', GA '+p.zip:'')+'</div>'
    +(p.price&&st!=='sold'?'<div class="gp-prop-price">$'+Number(p.price).toLocaleString()+'</div>':'')
